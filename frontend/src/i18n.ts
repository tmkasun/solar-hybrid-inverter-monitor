const dictionaries: Record<Language, Partial<Record<TranslationKey, string>>> = { en, si, ta };

export function normalizeLanguage(value: string | null | undefined): Language {
  const normalized = (value || "").trim().toLowerCase();
  if (normalized.startsWith("si")) return "si";
  if (normalized.startsWith("ta")) return "ta";
  return "en";
}

export function storedLanguage(getItem: (key: string) => string | null = key => localStorage.getItem(key)): Language {
  return normalizeLanguage(getItem(languageStorageKey));
}

function interpolate(template: string, params: TranslationParams = {}) {
  return template.replace(/\{(\w+)\}/g, (match, key) => String(params[key] ?? match));
}

function lookup(language: Language, key: TranslationKey, params?: TranslationParams) {
  return interpolate(dictionaries[language][key] || en[key] || key, params);
}

export function createI18n(language: Language) {
  const locale = languageOptions.find(option => option.value === language)?.locale || "en";
  const t = (key: TranslationKey, params?: TranslationParams) => lookup(language, key, params);
  return {
    language,
    locale,
    t,
    date(value: string | null | undefined) {
      return value ? new Date(value).toLocaleString(locale) : t("date.noLiveUpdate");
    },
    shortDateTime(value: string) {
      return new Date(value).toLocaleString(locale, { month: "short", day: "numeric", hour: "2-digit", minute: "2-digit" });
    },
    chartTime(value: string, longRange: boolean) {
      const date = new Date(value);
      return longRange ? date.toLocaleDateString(locale, { month: "short", day: "numeric", hour: "2-digit" }) : date.toLocaleTimeString(locale, { hour: "2-digit", minute: "2-digit" });
    },
    relativeTime(time: number, now: number) {
      const diffSeconds = Math.round((time - now) / 1000);
      const absSeconds = Math.abs(diffSeconds);
      const [unit, secondsPerUnit] = relativeTimeUnits.find(([, seconds]) => absSeconds >= seconds) || ["second", 1];
      return new Intl.RelativeTimeFormat(locale, { numeric: "always" }).format(Math.round(diffSeconds / secondsPerUnit), unit);
    },
  };
}

export type I18n = ReturnType<typeof createI18n>;

export function metricLabel(i18n: I18n, id: string) {
  const cellMatch = id.match(/^bms_cell_(\d+)_voltage$/);
  if (cellMatch) return i18n.t("metric.cellVoltage", { cell: Number(cellMatch[1]) });
  const resistanceMatch = id.match(/^bms_cell_(\d+)_resistance_mohm$/);
  if (resistanceMatch) return i18n.t("metric.cellResistance", { cell: Number(resistanceMatch[1]) });
  const wireMatch = id.match(/^bms_cell_(\d+)_wire_resistance_mohm$/);
  if (wireMatch) return i18n.t("metric.cellWire", { cell: Number(wireMatch[1]) });
  return i18n.t(`metric.${id}` as TranslationKey);
}

